    def _backup_package_lists(self, managers: List[str]) -> Dict[str, str]:
        """Write each manager's installed-package listing to a timestamped
        file under ~/.cortex_cleaner_backups before destructive operations,
        so removals can later be audited or replayed.

        Returns:
            Dict mapping manager name to backup file path; only managers
            whose list command succeeded are included.
        """
        backups = {}
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        
        for manager_name in managers:
            manager = self._get_manager_by_name(manager_name)
            if not manager:
                continue
            
            try:
                backup_file = self.backup_dir / f"{manager_name}_packages_{timestamp}.txt"
                
                config = self.package_managers[manager_name]
                list_command = [manager.executable] + config["list_command"]
                
                result = _proc.run(list_command, text=True, timeout=60)
                
                if result.returncode == 0:
                    with open(backup_file, 'w', encoding='utf-8') as f:
                        f.write(f"# Package list backup for {manager_name}\n")
                        f.write(f"# Created: {datetime.now().isoformat()}\n")
                        f.write(f"# Command: {' '.join(list_command)}\n\n")
                        f.write(result.stdout)
                    
                    backups[manager_name] = str(backup_file)
                    self.logger.info(f"Created backup for {manager_name}: {backup_file}")
                
            except Exception as e:
                self.logger.error(f"Failed to backup {manager_name} package list: {e}")
        
        return backups
    
    def verify_package_manager_health(self, package_manager: str) -> HealthStatus:
        """Post-cleanup sanity check for one manager.

        Runs the manager's list command, probes cache-dir writability with a
        touch/unlink file, and adds tool-specific checks (npm doctor,
        pip check) where applicable.

        Returns:
            HealthStatus; is_healthy is True only when no issues were found.
        """
        manager = self._get_manager_by_name(package_manager)
        if not manager:
            return HealthStatus(False, ["Package manager not found"])
        
        issues = []
        recommendations = []
        
        try:
            config = self.package_managers[package_manager]
            test_command = [manager.executable] + config["list_command"]
            
            result = _proc.run(test_command, text=True, timeout=30)
            
            if result.returncode != 0:
                issues.append(f"Basic command failed: {result.stderr}")
            
            if manager.cache_path and manager.cache_path.exists():
                try:
                    test_file = manager.cache_path / ".health_check"
                    test_file.touch()
                    test_file.unlink()
                except Exception as e:
                    issues.append(f"Cache directory not writable: {e}")
            
            if package_manager == "npm":
                doctor_result = _proc.run([manager.executable, "doctor"], 
                                             text=True, timeout=60)
                if doctor_result.returncode != 0:
                    issues.append("npm doctor reported issues")
                    recommendations.append("Run 'npm doctor' for detailed diagnostics")
            
            elif package_manager == "pip":
                check_result = _proc.run([manager.executable, "check"], 
                                            text=True, timeout=30)
                if check_result.returncode != 0:
                    issues.append("pip check found dependency conflicts")
                    recommendations.append("Run 'pip check' to see dependency issues")
            
        except Exception as e:
            issues.append(f"Health check failed: {e}")
        
        is_healthy = len(issues) == 0
        return HealthStatus(is_healthy, issues, recommendations)
    
    def _get_manager_by_name(self, name: str) -> Optional[PackageManager]:
        """Look up a detected manager by name key; None when absent."""
        for manager in self.detected_managers:
            if manager.name == name:
                return manager
        return None
    
    def _get_cache_size(self, cache_path: Optional[Path]) -> int:
        """Recursive byte total for a cache dir; missing paths count 0."""
        if not cache_path or not cache_path.exists():
            return 0
        
        total_size = 0
        try:
            for root, dirs, files in os.walk(cache_path):
                for file in files:
                    file_path = Path(root) / file
                    try:
                        total_size += file_path.stat().st_size
                    except Exception:
                        continue
        except Exception:
            pass
        
        return total_size
    
    def get_stats(self) -> Dict[str, any]:
        """Get statistics about detected package managers."""
        stats = {
            "detected_managers": len(self.detected_managers),
            "managers": {}
        }
        
        for manager in self.detected_managers:
            cache_size = self._get_cache_size(manager.cache_path)
            stats["managers"][manager.name] = {
                "version": manager.version,
                "cache_path": str(manager.cache_path) if manager.cache_path else None,
                "cache_size": cache_size,
                "cache_size_human": self._format_bytes(cache_size),
                "is_healthy": manager.health_status == "healthy"
            }
        
        return stats
    
    def _format_bytes(self, bytes_count: int) -> str:
        """Format bytes into human-readable format."""
        count = float(bytes_count)
        for unit in ['B', 'KB', 'MB', 'GB', 'TB']:
            if count < 1024.0:
                return f"{count:.1f} {unit}"
            count /= 1024.0
        return f"{count:.1f} PB"

    def scan_caches(self, target_folders: Optional[List[str]] = None, 
                   include_python_projects: bool = False,
                   keep_recent_days: int = 7,
                   enabled_categories: Optional[List[str]] = None,
                   progress_callback: Optional[object] = None,
                   cancel_event: Optional[object] = None) -> List[Dict]:
        """Locate cleanable caches in manager-owned dirs or project trees.

        Without target_folders, reports each detected manager's global cache
        (regenerable downloads). With target_folders, walks those trees and
        matches directory names against PROJECT_CACHE_CATEGORIES.

        Args:
            target_folders: Folders to scan for project caches; None selects
                global package-manager cache scanning instead.
            include_python_projects: Accepted for compatibility; category
                selection is controlled via enabled_categories.
            keep_recent_days: Ignore files younger than this many days (0 = all).
            enabled_categories: Restrict scan to these category IDs
                ('python', 'node', ...); None means all.
            progress_callback: Called as fn(status_text, items_found, total_size).
            cancel_event: threading.Event-like; set() aborts the walk.

        Returns:
            List of resource dicts (schema in _scan_project_caches_in_folder
            and _scan_manager_cache).
        """
        self.detect_package_managers()
        resources = []
        
        if target_folders:
            for folder in target_folders:
                folder_path = Path(folder)
                if folder_path.exists():
                    proj_caches = self._scan_project_caches_in_folder(
                        folder_path,
                        keep_recent_days=keep_recent_days,
                        enabled_categories=enabled_categories,
                        progress_callback=progress_callback,
                        cancel_event=cancel_event
                    )
                    resources.extend(proj_caches)
        else:
            for manager in self.detected_managers:
                if manager.cache_path and manager.cache_path.exists():
                    cache_info = self._scan_manager_cache(manager, keep_recent_days)
                    if cache_info:
                        resources.append(cache_info)
        
        return resources
    
    def _scan_project_caches_in_folder(self, folder: Path, keep_recent_days: int = 0,
                                        enabled_categories: Optional[List[str]] = None,
                                        progress_callback: Optional[object] = None,
                                        cancel_event: Optional[object] = None) -> List[Dict]:
        """Walk `folder` matching directory names against PROJECT_CACHE_CATEGORIES.

        Dotted patterns (e.g. `.egg-info`) also match as name suffixes; each
        hit is reported as a project_cache resource and pruned from deeper
        descent. Loose .pyc/.pyo files are tallied into the running totals
        when the python category is active but emit no per-file resource.
        """
        resources = []
        cutoff_date = datetime.now() - timedelta(days=keep_recent_days) if keep_recent_days > 0 else None
        
        # Build active pattern lookup: pattern_name -> (category_id, description)
        pattern_map = {}
        target_cats = enabled_categories if enabled_categories else list(PROJECT_CACHE_CATEGORIES.keys())
        
        for cat_id in target_cats:
            if cat_id in PROJECT_CACHE_CATEGORIES:
                cat_info = PROJECT_CACHE_CATEGORIES[cat_id]
                for pat, desc in cat_info["patterns"].items():
                    pattern_map[pat] = (cat_id, desc)
        
        def _match_dir(d_name: str) -> Optional[tuple]:
            if d_name in pattern_map:
                return pattern_map[d_name]
            for pat, (cat_id, desc) in pattern_map.items():
                if pat.startswith(".") and d_name.endswith(pat):
                    return (cat_id, desc)
                if pat.endswith("*") and d_name.startswith(pat.rstrip("*")):
                    return (cat_id, desc)
            return None
            """_match_dir."""
            """_match_dir."""
        
        total_items = 0
        total_size = 0
        
        try:
            for root, dirs, files in os.walk(folder):
                if cancel_event and getattr(cancel_event, 'is_set', lambda: False)():
                    break
                
                dirs_to_remove = []
                for d in dirs:
                    dir_path = Path(root) / d
                    match_result = _match_dir(d)
                    
                    if match_result:
                        cat_id, description = match_result
                        try:
                            dir_size, file_cnt = self._get_dir_size(dir_path, cutoff_date)
                            if file_cnt > 0:
                                total_size += dir_size
                                total_items += 1
                                
                                project_name = dir_path.parent.name or folder.name
                                resources.append({
                                    "type": "project_cache",
                                    "category": cat_id,
                                    "path": str(dir_path),
                                    "name": project_name,
                                    "cache_name": d,
                                    "size": dir_size,
                                    "file_count": file_cnt,
                                    "description": f"{description} ({d})",
                                    "manager_name": PROJECT_CACHE_CATEGORIES.get(cat_id, {}).get("label", cat_id.title())
                                })
                                
                                if progress_callback and callable(progress_callback):
                                    progress_callback(
                                        f"Found {d} in {project_name} ({self._format_bytes(dir_size)})",
                                        total_items,
                                        total_size
                                    )
                            dirs_to_remove.append(d)
                        except Exception:
                            pass
                
                for d in dirs_to_remove:
                    dirs.remove(d)
                
                # Loose .pyc/.pyo outside __pycache__: tally only, no resource
                if "python" in target_cats:
                    for file in files:
                        if file.endswith(('.pyc', '.pyo')):
                            file_path = Path(root) / file
                            try:
                                file_stat = file_path.stat()
                                if cutoff_date is None or datetime.fromtimestamp(file_stat.st_mtime) < cutoff_date:
                                    total_size += file_stat.st_size
                            except Exception:
                                pass
        except Exception as e:
            self.logger.error(f"Error scanning folder {folder}: {e}")
        
        return resources
    
    def _scan_manager_cache(self, manager: PackageManager, keep_recent_days: int) -> Optional[Dict]:
        """Summarize one manager's global cache as a resource dict; None when
        the dir is missing or holds no eligible files.
        """
        if not manager.cache_path or not manager.cache_path.exists():
            return None
        
        try:
            total_size, file_count = self._get_dir_size(
                manager.cache_path, 
                datetime.now() - timedelta(days=keep_recent_days)
            )
            
            if file_count > 0:
                return {
                    "type": "package_manager_cache",
                    "path": str(manager.cache_path),
                    "name": manager.name,
                    "size": total_size,
                    "file_count": file_count,
                    "description": f"{manager.name} v{manager.version} cache",
                    "manager_name": manager.name
                }
        except Exception as e:
            self.logger.error(f"Error scanning cache for {manager.name}: {e}")
        
        return None
    
    def _get_dir_size(self, path: Path, cutoff_date: Optional[datetime] = None) -> tuple:
        """Total bytes and file count under path.

        Files modified at/after cutoff_date are excluded; callers use this to
        keep recent cache entries and count only stale ones.
        """
        total_size = 0
        file_count = 0
        
        try:
            for root, dirs, files in os.walk(path):
                for file in files:
                    file_path = Path(root) / file
                    try:
                        file_stat = file_path.stat()
                        
                        if cutoff_date:
                            if datetime.fromtimestamp(file_stat.st_mtime) >= cutoff_date:
                                continue
                        
                        total_size += file_stat.st_size
                        file_count += 1
                    except Exception:
                        pass
        except Exception as e:
            self.logger.debug(f"Error calculating size for {path}: {e}")
        
        return total_size, file_count
    
    def clean_cargo_project(self, target_path: Path, dry_run: bool = True) -> Dict:
        """Run ``cargo clean`` for a Rust project's target dir.

        Args:
            target_path: Path to the target folder (parent must contain Cargo.toml).
            dry_run: When True, only estimates size without deleting.

        Returns:
            Dict with freed/removed/errors, cargo-aware message.
        """
        manifest = target_path.parent / "Cargo.toml"
        if manifest.exists():
            if dry_run:
                size, cnt = self._get_dir_size(target_path, None)
                return {"freed": size, "removed": cnt, "errors": [],
                        "note": f"Dry-run: cargo clean would free {self._format_bytes(size)}"}
            try:
                result = _proc.run(
                    ["cargo", "clean", "--manifest-path", str(manifest)],
                    text=True, timeout=120,
                )
                if result.returncode == 0:
                    # cargo clean removes the target dir itself; freed is pre-size
                    # Already computed by caller; here we just confirm success.
                    return {"freed": 0, "removed": 1, "errors": []}
                return {"freed": 0, "removed": 0, "errors": [result.stderr.strip() or "cargo clean failed"]}
            except Exception as e:
                return {"freed": 0, "removed": 0, "errors": [str(e)]}
        # Fallback to plain file deletion
        return self._cleanup_python_cache(target_path, dry_run)

    def auto_discover_project_caches(
        self,
        enabled_categories: Optional[List[str]] = None,
        keep_recent_days: int = 7,
        progress_callback: Optional[object] = None,
        cancel_event: Optional[object] = None,
        max_depth: int = 4,
    ) -> List[Dict]:
        """Walk all fixed drives for PROJECT_CACHE_CATEGORIES without manual folder.

        Scans common code roots (D:\\code, C:\\Users\\...\\code, ...) plus the
        root of each fixed drive shallowly (max_depth) to catch the 21.9GB
        NexusExplorer/target etc. cases where the user never picked a folder.

        Returns:
            Same resource dicts as scan_caches(target_folders=...).
        """
        from pathlib import Path as _P
        try:
            import psutil
            partitions = psutil.disk_partitions(all=False)
            drive_roots = [p.mountpoint for p in partitions if "fixed" in p.opts.lower() or p.fstype.lower() in ("ntfs", "refs") or (platform.system() == "Windows" and len(p.mountpoint) == 3 and p.mountpoint[1] == ":")]
            # Fallback on Windows if opts empty: enumerate C:, D: ...
            if not drive_roots and platform.system() == "Windows":
                for letter in "CDEFGHIJKLMNOPQRSTUVWXYZ":
                    d = f"{letter}:\\"
                    if _P(d).is_dir():
                        drive_roots.append(d)
        except Exception:
            drive_roots = [str(Path.home().drive) or "C:\\"] if platform.system() == "Windows" else [str(Path.home())]

        # Prefer known code roots first (fast, high hit rate across all drives)
        code_roots: list[str] = []
        try:
            from cortex_unified.analyzers.project_cache_scanner import _known_code_roots
            for p in _known_code_roots():
                code_roots.append(str(p))
        except Exception:
            for cand in [
                Path.home() / "code",
                Path.home() / "Projects",
                Path.home() / "Main_projects",
                Path.home() / "Documents" / "code",
                Path.home() / "source" / "repos",
            ]:
                try:
                    if cand.is_dir():
                        code_roots.append(str(cand))
                except OSError:
                    continue
        # If we have code roots, scan those deeply; otherwise shallow scan drive roots
        if code_roots:
            return self.scan_caches(
                target_folders=code_roots,
                keep_recent_days=keep_recent_days,
                enabled_categories=enabled_categories,
                progress_callback=progress_callback,
                cancel_event=cancel_event,
            )
        # Shallow drive scan with early pruning - use the dedicated scanner if available
        try:
            from cortex_unified.analyzers.project_cache_scanner import ProjectCacheScanner
            scanner = ProjectCacheScanner(
                enabled_categories=enabled_categories,
                keep_recent_days=keep_recent_days,
            )
            return scanner.scan_fixed_drives(
                progress_callback=progress_callback,
                cancel_event=cancel_event,
                max_depth=max_depth,
            )
        except ImportError:
            # Fallback: scan drive roots with our own logic (depth-limited)
            resources: List[Dict] = []
            for root in drive_roots:
                if cancel_event and getattr(cancel_event, 'is_set', lambda: False)():
                    break
                try:
                    rp = _P(root)
                    if rp.is_dir():
                        resources.extend(
                            self._scan_project_caches_in_folder(
                                rp,
                                keep_recent_days=keep_recent_days,
                                enabled_categories=enabled_categories,
                                progress_callback=progress_callback,
                                cancel_event=cancel_event,
                            )
                        )
                except Exception:
                    continue
            return resources

    def cleanup_caches(self, resources: List[Dict], dry_run: bool = True,
                       progress_callback: Optional[object] = None,
                       cancel_event: Optional[object] = None) -> Dict:
        """Dispatch each scanned resource to its cleaner and aggregate results.

        Args:
            resources: Resource dicts as produced by scan_caches.
            dry_run: Passed through to the per-type cleaners; only some
                managers honor it (see _cleanup_manager_cache).
            progress_callback: Called as fn(done, total, freed_bytes).
            cancel_event: Set to stop before processing the next resource.

        Returns:
            Summary dict with success/freed/removed/errors plus per-resource
            results keyed by resource name.
        """
        total_freed = 0
        total_removed = 0
        errors = []
        results = {}
        total_count = len(resources)
        
        for idx, resource in enumerate(resources):
            if cancel_event and getattr(cancel_event, 'is_set', lambda: False)():
                break
                
            try:
                resource_type = resource.get("type")
                path = Path(resource.get("path", ""))
                
                if not path.exists():
                    continue
                
                if resource_type in ("python_cache", "project_cache"):
                    # Prefer cargo clean for Rust target folders
                    if path.name == "target" and (path.parent / "Cargo.toml").exists():
                        result = self.clean_cargo_project(path, dry_run)
                        # When cargo clean actually ran, we need freed estimate from scan
                        if not dry_run and not result.get("errors"):
                            result["freed"] = resource.get("size", 0)
                            result["removed"] = resource.get("file_count", 1)
                    else:
                        result = self._cleanup_python_cache(path, dry_run)
                elif resource_type == "package_manager_cache":
                    result = self._cleanup_manager_cache(
                        resource.get("manager_name"), 
                        dry_run
                    )
                else:
                    continue
                
                total_freed += result.get("freed", 0)
                total_removed += result.get("removed", 0)
                errors.extend(result.get("errors", []))
                results[resource.get("name", f"item_{idx}")] = result
                
                if progress_callback and callable(progress_callback):
                    progress_callback(idx + 1, total_count, total_freed)
                
            except Exception as e:
                error_msg = f"Error cleaning {resource.get('name', 'unknown')}: {e}"
                self.logger.error(error_msg)
                errors.append(error_msg)
        
        return {
            "success": len(errors) == 0,
            "freed": total_freed,
            "removed": total_removed,
            "errors": errors,
            "results": results,
            "dry_run": dry_run
        }
    
    def _cleanup_python_cache(self, cache_path: Path, dry_run: bool = True) -> Dict:
        """Delete every file under a project-cache directory.

        Contents (bytecode, tool/test caches, build outputs) are regenerated
        by the toolchain, so wholesale deletion is safe; the directory itself
        is removed only if it ends up empty.

        Args:
            cache_path: Cache directory to clean.
            dry_run: Count files/sizes without unlinking.

        Returns:
            Dict with freed bytes, removed count, errors, and dry_run echo.
        """
        freed = 0
        removed = 0
        errors = []
        
        if not cache_path.exists():
            return {"freed": 0, "removed": 0, "errors": []}
        
        try:
            for root, dirs, files in os.walk(cache_path):
                for file in files:
                    file_path = Path(root) / file
                    try:
                        file_size = file_path.stat().st_size
                        freed += file_size
                        removed += 1
                        
                        if not dry_run:
                            file_path.unlink()
                    except Exception as e:
                        errors.append(f"Could not remove {file_path}: {e}")
            
            # Try to remove empty directories
            if not dry_run:
                try:
                    if cache_path.exists() and not any(cache_path.iterdir()):
                        cache_path.rmdir()
                except Exception:
                    pass  # Directory not empty, that's okay
        
        except Exception as e:
            errors.append(f"Error cleaning {cache_path}: {e}")
        
        return {
            "freed": freed,
            "removed": removed,
            "errors": errors,
            "dry_run": dry_run
        }
    
    def _cleanup_manager_cache(self, manager_name: str, dry_run: bool = True) -> Dict:
        """Run the manager's native cache-clean command.

        Package lists are backed up first and freed space is inferred from
        before/after cache-size sampling. Only pip gets a true dry-run
        (reported as a would-free estimate); every other manager executes its
        real clean command regardless of dry_run.

        Args:
            manager_name: Key into self.package_managers.
            dry_run: Estimate-only for pip; ignored by other managers.

        Returns:
            Dict with freed/removed/errors, plus the backup path when a clean
            actually ran.
        """
        manager = self._get_manager_by_name(manager_name)
        if not manager:
            return {
                "freed": 0,
                "removed": 0,
                "errors": [f"Package manager {manager_name} not found"]
            }
        
        try:
            backup_result = self._backup_package_lists([manager_name])
            
            cache_size_before = self._get_cache_size(manager.cache_path)
            
            if dry_run:
                # pip has no dry-run mode; report current size as the estimate
                if manager_name in ["pip"]:
                    return {
                        "freed": cache_size_before,
                        "removed": 1,
                        "errors": [],
                        "note": f"Dry-run: Would clean {self._format_bytes(cache_size_before)}"
                    }
            
            config = self.package_managers[manager_name]
            clean_command = [manager.executable] + config["cache_clean_command"]
            
            result = _proc.run(clean_command, text=True, timeout=120)
            
            if result.returncode != 0:
                return {
                    "freed": 0,
                    "removed": 0,
                    "errors": [f"Clean command failed: {result.stderr}"]
                }
            
            cache_size_after = self._get_cache_size(manager.cache_path)
            freed = cache_size_before - cache_size_after
            
            return {
                "freed": freed,
                "removed": 1,
                "errors": [],
                "backup": backup_result.get(manager_name)
            }
        
        except Exception as e:
            return {
                "freed": 0,
                "removed": 0,
                "errors": [f"Cleanup failed: {e}"]
            }