"""Detects installed package managers and clears their regenerable caches.

Every cache touched here (downloaded wheels, tarballs, build artifacts) is
rebuilt or refetched by the tool on demand, so clearing only costs bandwidth
on the next install. Also scans project folders for per-project cache dirs
via PROJECT_CACHE_CATEGORIES.
"""

